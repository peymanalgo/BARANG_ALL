    public static string Tr(string? en)
    {
        if (string.IsNullOrEmpty(en)) return en ?? "";
        if (Map.TryGetValue(en, out string? es)) return es;
        Match m = DaysAgo().Match(en);
        if (m.Success) return $"hace {m.Groups[1].Value} d";
        m = HoursAgo().Match(en);
        if (m.Success) return $"hace {m.Groups[1].Value} h";
        m = MinutesAgo().Match(en);
        if (m.Success) return $"hace {m.Groups[1].Value} min";
        m = UnreadCount().Match(en);
        if (m.Success) return $"{m.Groups[1].Value} sin leer";
        m = NotificationsCount().Match(en);
        if (m.Success) return $"{m.Groups[1].Value} notificaciones";
        m = DraftOrdersCount().Match(en);
        if (m.Success) return $"{m.Groups[1].Value} pedidos en borrador";
        return en;
    }

